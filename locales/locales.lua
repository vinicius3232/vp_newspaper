-- Idioma ativo padrão
CurrentLang = 'pt'

function _U(str, ...)
    if Locales[CurrentLang] and Locales[CurrentLang][str] then
        return string.format(Locales[CurrentLang][str], ...)
    elseif Locales['en'] and Locales['en'][str] then
        return string.format(Locales['en'][str], ...)
    end
    return str
end

-- Compatibilidade retroativa para a NUI original
NMLocales = {
    CurrentLanguage = CurrentLang,
    Texts = Locales
}
